import { useCallback, useEffect, useRef, useState } from "react";
import { ArrowUp, Bot, CircleAlert, Lightbulb, MessageSquareText, Sparkles, UserRound } from "lucide-react";
import { assistantService } from "../services/banking.js";
import { useAuth } from "../app/AuthContext.jsx";
import { apiErrorMessage } from "../api/client.js";
import PageHeader from "../components/PageHeader.jsx";
import Panel from "../components/Panel.jsx";

const suggestions = [
  "Summarize recent banking activity",
  "What are common signs of a suspicious transfer?",
  "Explain the difference between savings and current accounts",
  "How does a loan EMI work?",
];

export default function Assistant() {
  const { isDemo } = useAuth();
  const [messages, setMessages] = useState(isDemo ? [{ role: "assistant", content: "Hello. I’m IntelliBank Assistant. I can help explain banking concepts and answer supported account questions. I cannot initiate transactions or make financial decisions." }] : []);
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const endRef = useRef(null);
  const loadHistory = useCallback(async () => {
    if (!isDemo) {
      try { setMessages((await assistantService.history()).data); }
      catch (historyError) { setError(apiErrorMessage(historyError)); }
    }
  }, [isDemo]);
  useEffect(() => { loadHistory(); }, [loadHistory]);
  useEffect(() => { endRef.current?.scrollIntoView({ behavior: "smooth" }); }, [messages, loading]);

  async function sendMessage(text = input) {
    const prompt = text.trim();
    if (!prompt || loading) return;
    setInput("");
    setError("");
    setMessages((items) => [...items, { role: "user", content: prompt }]);
    setLoading(true);
    try {
      if (isDemo) {
        await new Promise((resolve) => setTimeout(resolve, 650));
        setMessages((items) => [...items, { role: "assistant", content: /transfer|deposit|withdraw|pay/i.test(prompt)
          ? "I can’t initiate or approve financial transactions. Please use an authenticated banking channel and verify details before proceeding."
          : "This is a demo response. The production assistant can answer only supported, authenticated, ownership-checked banking questions. For account-specific information, sign in with a customer account. No financial action has been taken." }]);
      } else {
        const { data } = await assistantService.ask(prompt);
        setMessages((items) => [...items, { role: "assistant", content: data.answer }]);
      }
    } catch (requestError) {
      setError(apiErrorMessage(requestError));
      setMessages((items) => items.filter((item, index) => !(item.role === "user" && index === items.length - 1)));
    } finally { setLoading(false); }
  }

  return <div className="page-stack assistant-page">
    <PageHeader eyebrow="INTELLIBANK AI" title="Banking assistant" description="Read-only banking guidance with controlled backend integration." />
    {isDemo && <div className="demo-notice"><CircleAlert size={16} /> Demo assistant responses are illustrative and not generated by a live AI provider.</div>}
    <div className="assistant-layout">
      <Panel title="Conversation" description={isDemo ? "Demo mode" : "Connected to the authenticated assistant API"} className="chat-panel">
        <div className="chat-messages">
          {messages.length === 0 && <div className="chat-welcome"><span className="bot-orb"><Bot size={25} /></span><h2>How can I help?</h2><p>Ask a supported banking question or choose a suggestion to get started.</p></div>}
          {messages.map((message, index) => <div className={`chat-message ${message.role}`} key={`${message.role}-${index}`}>
            <span className="chat-avatar">{message.role === "assistant" ? <Bot size={17} /> : <UserRound size={17} />}</span>
            <div className="chat-bubble">{message.content}</div>
          </div>)}
          {loading && <div className="chat-message assistant"><span className="chat-avatar"><Bot size={17} /></span><div className="chat-bubble typing"><i /><i /><i /></div></div>}
          <div ref={endRef} />
        </div>
        {error && <div className="inline-error chat-error"><CircleAlert size={16} />{error}</div>}
        <form className="chat-composer" onSubmit={(event) => { event.preventDefault(); sendMessage(); }}>
          <textarea value={input} onChange={(event) => setInput(event.target.value)} maxLength={2000} rows={2} placeholder="Ask a banking question…" aria-label="Message" onKeyDown={(event) => { if (event.key === "Enter" && !event.shiftKey) { event.preventDefault(); sendMessage(); } }} />
          <button className="send-button" disabled={!input.trim() || loading} aria-label="Send message"><ArrowUp size={19} /></button>
        </form>
        <p className="chat-disclaimer">Do not share passwords, full card numbers, or authentication codes. The assistant does not execute transactions.</p>
      </Panel>
      <aside className="assistant-side">
        <Panel title="Suggested questions"><div className="suggestion-list">{suggestions.map((item) => <button key={item} onClick={() => sendMessage(item)}><MessageSquareText size={16} />{item}</button>)}</div></Panel>
        <Panel title="Assistant safeguards"><div className="guidance-list">
          <div className="guidance-item"><span className="mini-icon teal"><Lightbulb size={17} /></span><span><strong>Ownership first</strong><small>Account-specific data requires authenticated ownership checks.</small></span></div>
          <div className="guidance-item"><span className="mini-icon blue"><Sparkles size={17} /></span><span><strong>Read-only by design</strong><small>Responses cannot create payments or move funds.</small></span></div>
          <div className="guidance-item"><span className="mini-icon amber"><CircleAlert size={17} /></span><span><strong>Verify important guidance</strong><small>AI responses may be incomplete; consult official bank policy.</small></span></div>
        </div></Panel>
      </aside>
    </div>
  </div>;
}
